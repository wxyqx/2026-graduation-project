SYSTEM_HEAD = "你是一名资深的招聘面试官，负责把一场面试的对话逐字稿，整理成一份书面的面试评价。"

OUTPUT_LOCK = """【输出铁律】
1. 只输出面试评价正文本身，从"基本信息确认："开始、到第 7 项的答案结束。
2. 不要输出任何前言、解释、结语、问候、总结，不要写"好的""以下是""希望对你有帮助"这类话。
3. 不要加 markdown 代码块围栏（```），不要加任何多余的空行或符号。
4. 严格照模板的小节标题、题面行原文、编号输出，不要增删小节（没有"亮点""风险""综合评价""录用建议""打分"这类东西）。
   **题面行必须逐字照抄上面模板里的原文**（包括括号里的面试官问法），不要改动、不要缩写、不要补漏。范文里的题面行是历史版本，只可参考其**答案行的笔法**，不要照抄范文的题面行。"""


def build_system_prompt() -> str:
    """组装系统消息：人设 + 模板 + 写法文风 + 范文 + 输出铁律。"""
    return (
        f"{SYSTEM_HEAD}\n\n"
        f"===== 输出模板（照排，题面行原样保留，答案写在每题下方）=====\n{TEMPLATE}\n\n"
        f"{WRITING_RULES}\n\n"
        f"===== 参考范文（只学它答案行的笔法：怎么开场、怎么压缩、怎么正向接住；"
        f"题面行一律以上面模板的原文为准，不要照抄范文的题面行）=====\n{SAMPLE}\n\n"
        f"{OUTPUT_LOCK}"
    )


def build_user_prompt(transcript: str, *, strict: bool = False) -> str:
    """组装用户消息：逐字稿正文 + 任务。strict=True 是换配置重试时的加强版。"""
    body = (
        "下面是一场面试的对话逐字稿。请据此写一份面试评价。\n"
        "注意：逐字稿是面试官和候选人的口语对话；`xyq`、`夏雨泉` 等是面试官，另一个名字是候选人；"
        "带括号的时间戳只是转写标记，不要写进评价。\n\n"
        "===== 逐字稿开始 =====\n"
        f"{transcript[:MAX_TRANSCRIPT_CHARS]}\n"
        "===== 逐字稿结束 =====\n\n"
        "现在按系统消息里的模板、写法和文风，输出这份面试评价。"
    )
    if strict:
        body += (
            '\n\n再强调一次：只输出评价正文本身，从"基本信息确认："开始，'
            "不要有任何前言、解释或代码块标记。"
        )
    return body


# 模型爱在输出外面加的围栏和前言，这里清理掉
_FENCE = re.compile(r"^\s*```[a-zA-Z]*\s*|\s*```\s*$", re.MULTILINE)
# 开头的「好的，以下是…：」这类话（只吃掉不含评价正文的一行）
_PREFACE = re.compile(
    r"^\s*(好的|当然|没问题)[，,].{0,40}?(如下|以下|评价)[：:]\s*\n+",
    re.MULTILINE,
)


def clean_output(text: str) -> str:
    """把模型可能多说的前言和围栏清掉，只留评价正文。"""
    out = _FENCE.sub("", text or "").strip()
    out = _PREFACE.sub("", out)
    # 万一它把正文包在 ``` 里、围栏只剩一边，再兜一次
    if out.startswith("```"):
        out = re.sub(r"^```[a-zA-Z]*\s*", "", out)
    if out.endswith("```"):
        out = out[: -3]
    return out.strip()


async def evaluate(configs: list[AiApiConfig], transcript: str, *, idx: int = 0) -> dict:
    """把一份逐字稿交给 AI，返回 {text, config_used}。

    多个 AI 配置轮流用：先试 idx%n 那个，失败了换下一个再试一次（照搬 ai_screen 的做法）。
    两次都失败就抛 LlmError，由路由层翻成 502。
    """
    n = len(configs)
    if n == 0:
        raise llm.LlmError("没有可用的 AI 配置")

    system_prompt = build_system_prompt()
    last_err: Exception | None = None

    for attempt, cfg in enumerate((configs[idx % n], configs[(idx + 1) % n])):
        try:
            user_prompt = build_user_prompt(transcript, strict=(attempt > 0))
            content = await llm.chat(cfg, system_prompt, user_prompt)
            text = clean_output(content)
            if not text:
                last_err = llm.LlmError(f"[{cfg.name}] AI 返回了空内容")
                continue
            return {"text": text, "config_used": cfg.name}
        except llm.LlmError as e:
            last_err = e
            continue

    raise last_err or llm.LlmError("AI 调用失败")
