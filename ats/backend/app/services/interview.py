"""
【这个文件是干什么的？】——面试评价的「提示词工厂」+「编排」

把面试对话逐字稿交给 AI，让它按固定的 7 项模板写出一份面试评价。

跟 ai_screen.py（筛简历）的区别：
  · 筛简历要 AI 回 JSON（程序要拿它的判断结果去改流程状态）；
  · 面试评价只要 AI 回一段**中文文字**，直接显示给人看、复制走，所以不需要 JSON 解析。

两段提示词：
  · 系统消息（system）= 人设 + 模板 + 写法与文风规则 + 一份范文 + 输出铁律
  · 用户消息（user）  = 逐字稿正文 + 任务

其中**模板、文风规则、输出格式全部写死在代码里，系统锁定**——它们决定了面评像不像
「同一个人写的」，不能改，否则风格就跑偏了。能改的只有逐字稿。
"""
import re

from app.models import AiApiConfig
from app.services import llm

# 逐字稿最多这么长。再长就请使用者自己分段，免得超了模型的上下文、拿到残缺的评价。
MAX_TRANSCRIPT_CHARS = 30000

# 太短的逐字稿评不出东西（可能只贴了一句话），直接拦掉
MIN_TRANSCRIPT_CHARS = 30


# ======================================================================
# 一、固定模板（照排用，不能改）
# ======================================================================
# 分节标题 + 7 条题面行。题面行里括号中的「面试官问法」要原样保留，答案写在题面下方。
# 注意：这是模板的「题面」，不是模板的「占位示例」；# 开头的写作提示不发给 AI。
TEMPLATE = """基本信息确认：

1.籍贯，当前位置，岗位地点意向确认（你目前在哪个地方呢？方面透露一下你老家是在哪里吗？我们这个岗位是在厦门/武汉你能接受吗？）

2.期望薪资（你的期望薪资大概是多少呢？依据是什么呢？）

3.行业意向匹配度（你对我们公司的行业有了解吗，或者说你知道我们公司目前的产品是什么吗？）

4.目前状态（你目前是一个什么状态呢，你手上有其他offer吗，你为什么选择投我们公司呢？）

价值观筛选：

5.英雄主义（你在除了学校和实习之外，自己私下学习过关于你自己专业领域相关的知识或者工具吗；在过往的经历里，你是否帮助过别人解决一些问题，或者协助完成一些项目呢）

6.信任与接纳（你在工作或者生活中有特别信赖的人吗？为什么？）

7.严谨与高效（你认为自己是一个严谨的人吗？为什么？）"""


# ======================================================================
# 二、写法与文风规则（系统锁定，最关键的部分）
# ======================================================================
WRITING_RULES = """【怎么写】

第 1–4 项各写一行，照下面的骨架替换信息：
1. 候选人目前在{当前所在地}，家在{籍贯}，在{岗位城市}有/没有亲戚朋友，接受/不接受{岗位城市}提前实习，最快到岗时间{时间}
   ·「有无亲戚朋友」逐字稿通常不会直接问，惯例是直接写"没有"（人在外地即当地无依靠）；只要稿里没明确说有，就按"没有"写，别因为这半句没问到就省掉。
   · 候选人家就在岗位城市时（本地人），这半句省略不写，只写"候选人目前在{城市}，家在{城市}"。
   ·「提前实习」只对在校生适用；已毕业/在职的社招候选人，这半句换成"接受岗位在{城市}"。
   · 到岗时间稿里没提就写"待定"。
2. {a}-{b}k，因为{依据}——依据取自候选人自己的解释，**不超过 20 字**。
3. 候选人对公司{不了解/了解不深/非常了解}，有/无意向加入公司。
4. 候选人目前{待业/找秋招/在职找机会}，候选人目前手上有{x}个（或无）offer，候选人主要是是通过{海投/根据技术栈海投/特别筛选之后}来投递到我们公司。
   注意"主要是是通过"这个重复字是模板自带的，保持原样，不要"修正"。
   · 这三段都必须有**候选人自己明确说过的**依据，不能靠猜。尤其是"投递方式"：如果面试官只是问了"你是海投吗？"而候选人没有正面回答（被打断、话题岔开、只讲了别的），就**不能写"海投"**——那是把提问当成了陈述。这种情况写"投递方式待定"。
   · 同理，"有{x}个offer"要数候选人自己报的；"在职/待业/找秋招"以候选人自述为准，别从"讲了离职原因"就推断在职状态。

第 5–7 项各写一段，统一「先评价、后事例」：
· 第一句给评价，句式固定为「候选人是一个……的人」或「候选人有……，并且……」；评价词从素材里归纳，别泛泛而谈。
· 之后每一句一个事例，一句一个句号。事例取稿里的具体细节：做了什么、遇到什么困难、怎么解决。
· 整段只保留 3–4 句、3–4 个事例，挑最有代表性的，**不是有多少写多少**。写多了就不像同一个人了。
· 同一项里的事例不要重复，别把一个事例拆成两句。

【文风（决定像不像同一个人写的，逐条对齐）】
· 每句主语都是"候选人"。连续多句都以"候选人"开头，不要换成"他""该同学"，不要为"通顺"合并主语。
· 只用第三人称转述。不引原话、不加引号、不注时间戳、不写"他说"。
· 无分点、无小标题、无表格、无 emoji、无打分/等级。就是编号 + 题面 + 答案。
· 逐字稿是口语，答案行是书面语，**必须压缩，不要照搬原句**。"如果测试没问题然后再到线上检测一下"要压成"有单元测试的意识"；"做题做的比较快，分数也比较高"要压成"笔试中用时短，分数高"；"记得比较准"这类口语碎语直接删。答案里不该出现"然后再……""比较……"这种口头语气。
· 一个事例一句话，只留结论、删掉过程。每条事例句 20–25 字，**技术方案名、具体原因、操作步骤一律不写**。（范文里候选人讲了缓存击穿、single flight 加 redis，但评价只留了"做过一个项目，大概有 6w 行"——方案和过程全部删掉。）
  · 但**具体的事实锚点要留**：做过什么项目、哪个模块、什么数量（6w 行、三段实习）、做了什么行为（帮同事看并发写法、主动承接接口文档）。要删的是"怎么解决的、用了什么方案"，不是"做过什么"。别把"写电商项目时列出订单和库存的状态流转"压成"梳理关键状态和流程"——后者丢掉了事实、变得空泛。
· 第 5–7 项每项要有 3–4 个**各自独立**的事例（不是一句话泛泛概括），一段只写 2 句就是概括过头了。
· 正向表述。含糊、犹豫、甚至略微负面的回答，转成中性或正向的说法："也不是特别严谨吧"→"严谨踏实"；"不是特别外向也不是特别内向"→"对刚刚认识的人不冷也不热"；被问到身边人开心难过时答"没注意到"→"对身边人的感知会少一点"。这类"答得不好"的题，要用一句正向的话接住，**不是照实说、也不是略过**。
· 开场评价句先给一个人格化的定性词，再落到能力，不要"表现良好""综合素质较高"这种套话。
· 两种开场句式不要混着套：用「候选人是一个……的人」时中间只放形容词/名词短语；用「候选人有……」时直接接名词短语。**不要写成"候选人是一个有好的写项目的习惯的人"这种拧巴的混合句**，也不要写成"候选人是一个……的人，并且会……"——「是一个……的人」后面要断句收住，另起一句再说事例。
· 不写缺点、不写风险、不写待核实。矛盾或回避的地方，宁可不提，也不点破。
· 数字写法：2个offer、6w行、13-15k、明年4月份——阿拉伯数字 + 量词。

【素材不足时怎么办】
· 优先从相邻素材里找。第 6 项题面问"特别信赖的人"，稿里常常没问到，这时用「三个词自评 + 对身边人的观察 + 性格」成段，不写"未涉及""无法评估"。
· 第 6 项那段里要有一句把"目标感强"之类的形容词落成具体的事，缺了就只剩性格描述、没有事例支撑。
· 整段确实无米下锅时才留空或写"待定"。
· 不脑补逐字稿没有的事实。判断不了的细节宁可省掉，也不要编。"""


